const path = require('node:path');
const ts = require('typescript');
const source = fs.readFileSync(path.resolve(__dirname, '../src/lib/cloud-sync.ts'), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const compiled = { exports: {} };
new Function('require', 'module', 'exports', js)(require, compiled, compiled.exports);
const { contactDiff: diff, mergeBrowserContacts: merge } = compiled.exports;
const make = (id, name = 'A') => ({ id, fullName:name, jobTitle:'', companyName:'', email:'', phone:'', website:'', address:'', notes:'', confidenceScore:'High', preview:'', sourceName:'test.webp', createdAt:'2026-11-23T00:00:00.000Z' });
