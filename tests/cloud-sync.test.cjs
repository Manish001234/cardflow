test('load Cloud sync utility', () => assert.equal(typeof diff, 'function'));
test('new cards produce one upsert', () => assert.deepEqual(diff([], [make(id1)]), [{type:'upsert', card:make(id1)}]));
test('identical snapshots produce no operations', () => assert.deepEqual(diff([make(id1)], [make(id1)]), []));
test('name correction produces upsert', () => assert.equal(diff([make(id1)], [make(id1,'Corrected')])[0].card.fullName,'Corrected'));
test('deleted card produces id-scoped deletion', () => assert.deepEqual(diff([make(id1)], []), [{type:'delete',id:id1,expectedRevision:0}]));
test('deleting one does not delete another', () => assert.deepEqual(diff([make(id1),make(id2)], [make(id2)]), [{type:'delete',id:id1,expectedRevision:0}]));
test('bulk updates preserve unchanged IDs', () => assert.equal(diff([make(id1),make(id2)], [make(id1,'New'),make(id2)]).length,1));
test('favorites cause a contact upsert', () => assert.equal(diff([make(id1)], [{...make(id1),favorite:true}]).length,1));
test('tags cause contact upsert', () => assert.equal(diff([make(id1)], [{...make(id1),tags:['Lead']}]).length,1));
test('reviewedAt change is synced', () => assert.equal(diff([make(id1)], [{...make(id1),reviewedAt:'2026-11-23T00:00:00.000Z'}]).length,1));
test('browser merge leaves existing cloud row untouched', () => assert.deepEqual(merge([make(id1,'Cloud')], [make(id1,'Local')]), [make(id1,'Cloud')]));
test('browser merge adds previously unseen IDs', () => assert.equal(merge([make(id1)],[make(id2)]).length,2));
